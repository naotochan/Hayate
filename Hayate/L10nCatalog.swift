/// Translations for every UI language besides English and Japanese.
///
/// English and Japanese are the bilingual source of truth baked into every
/// `t(_:ja:)` call site (see `Localization.swift`) — they are never stored
/// here. Every other `ResolvedLanguage` looks up its English key in this
/// catalog; a missing key falls back to English by design (`ResolvedLanguage.t`).
///
/// Keys are the literal English string passed to `t(`. Call sites that used
/// to interpolate values directly now pass a `%d` / `%@` format string, so
/// the catalog entry must use the same placeholders in the same order as the
/// English source (see `t(_:ja:_:)`).
